    def _create_complete_role_dag(self) -> None:
        for index, role in enumerate(self.roles):
            self._create_role(role, index)
            if role == "concept_mapper":
                self._create_external_sanitized_ledger()
        aggregate = {
            "schema_version": "NCF-PRIMARY-ROLE-MANIFEST-SET-1.0.0",
            "protocol": self.ref(self.protocol_path),
            "manifests": [],
        }
        for role in self.roles:
            manifest = self.read_json(self.manifest_paths[role])
            aggregate["manifests"].append(
                {
                    "role": role,
                    "run_id": manifest["run_id"],
                    **self.ref(self.manifest_paths[role]),
                }
            )
        _write_json(self.aggregate_path, aggregate)

