    def _trace_accesses(
        self,
        inputs: list[dict[str, Any]],
        outputs: list[dict[str, Any]],
        prompt_ref: Mapping[str, Any],
        parent_ref: Mapping[str, Any],
    ) -> list[dict[str, Any]]:
        accesses: list[dict[str, Any]] = []

