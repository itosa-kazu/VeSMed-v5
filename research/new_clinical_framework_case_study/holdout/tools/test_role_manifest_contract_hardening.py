    def replace_input_content_ref(
        self, role: str, data_class: str, fresh_ref: Mapping[str, Any]
    ) -> None:
        manifest = self.manifest(role)
        input_row = next(row for row in manifest["inputs"] if row["data_class"] == data_class)
        for key in ("path", "sha256", "bytes"):
            input_row[key] = fresh_ref[key]
        trace_path = self.root / manifest["tool_trace"]["path"]
        trace = self.read_json(trace_path)
        access = next(
            row
            for row in trace["accesses"]
            if row["artifact_kind"] == "INPUT" and row["data_class"] == data_class
        )
        for key in ("path", "sha256", "bytes"):
            access[key] = fresh_ref[key]
        _write_json(trace_path, trace)
        manifest["tool_trace"] = self.ref(trace_path)
        self.write_manifest(role, manifest)

