import json
from pathlib import Path


OUT = Path(__file__).resolve().parent / "cases"
OUT.mkdir(parents=True, exist_ok=True)


def obs(axis_id, value, unit, source="", stage="presentation", use=True):
    return {
        "axis_id": axis_id,
        "value": value,
        "unit": unit,
        "source_text_value": source or str(value),
        "stage": stage,
        "evidence_stage": stage,
        "use_in_ranking": use,
    }


def case(case_id, pmid, pmcid, diagnosis, expected, demographics, observations, summary, risk_context=None, expected_manifolds=None):
    data = {
        "case_id": case_id,
        "source_pmid": pmid,
        "source_pmcid": pmcid,
        "source_url": f"https://pmc.ncbi.nlm.nih.gov/articles/{pmcid}/" if pmcid else "",
        "source_access_method": {
            "case_selection": "separate case-only agent, no atlas or ranking context",
            "ranking_copy_generation": "main-thread normalization into diagnosis-neutral axis observations",
        },
        "disease_label_per_paper": diagnosis,
        "expected_manifold": expected,
        "demographics": demographics,
        "snapshot_day": 0,
        "diagnostic_stage": "initial_workup",
        "presentation_summary": [summary],
        "risk_context": risk_context or [],
        "observations": observations,
        "record_only": [],
    }
    if expected_manifolds:
        data["expected_manifolds"] = expected_manifolds
    path = OUT / f"v5_case_{case_id}.json"
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


